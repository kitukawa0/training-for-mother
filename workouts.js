// Сколько раз повторяем круг упражнений для каждого уровня сложности.
// Если добавите больше упражнений в EXERCISES, эти числа стоит пересмотреть.
const ROUNDS = { easy: 3, hard: 2 };

// Сначала ищем .mp4, если его нет — пробуем .mov (например, видео прямо с iPhone).
// Для надёжного воспроизведения на всех устройствах (не только на iPhone/Mac,
// но и на компьютере с Windows, Android и телевизоре) лучше всё же перегонять
// видео в mp4 (H.264) — .mov проигрывается не везде одинаково стабильно.
const VIDEO_EXTENSIONS = ['mp4', 'mov'];

/** Возможные пути к видео пользователя для упражнения — см. папку videos/ */
function getVideoCandidates(exercise) {
  return VIDEO_EXTENSIONS.map(ext => `videos/${exercise.id}.${ext}`);
}

/** Лёгкая тренировка — только упражнения без инвентаря.
 *  Тяжёлая — весь список, включая гантели и резинку. */
function getDifficultyPool(difficulty) {
  return difficulty === 'hard' ? EXERCISES : EXERCISES.filter(ex => !ex.equipment);
}

/** Формирует тренировку на день: повторяет круг упражнений нужное число раз подряд */
function generateWorkout(difficulty) {
  const pool = getDifficultyPool(difficulty);
  const rounds = ROUNDS[difficulty] || 1;
  let sequence = [];
  for (let r = 0; r < rounds; r++) {
    sequence = sequence.concat(pool);
  }
  return sequence;
}

function getWorkoutTotalSeconds(exercises) {
  return exercises.reduce((sum, ex) => sum + ex.duration, 0);
}
